// Bundle src/entry.ts into dist/index.js — one file, Node only, sql.js
// WebAssembly inlined (same approach as the upstream extension) — and write
// THIRD_PARTY_NOTICES.md from the packages that actually went into the bundle.
import * as fs from "node:fs";
import * as path from "node:path";
import { build } from "esbuild";

const result = await build({
    entryPoints: ["src/entry.ts"],
    bundle: true,
    platform: "node",
    target: "node20",
    format: "esm",
    loader: { ".wasm": "binary" },
    outfile: "dist/index.js",
    metafile: true,
    banner: {
        js: "import { createRequire as __cr } from 'module'; import { fileURLToPath as __furl } from 'url'; import { dirname as __dn } from 'path'; const require = __cr(import.meta.url); const __filename = __furl(import.meta.url); const __dirname = __dn(__filename);",
    },
    logLevel: "info",
});

const pkgs = new Set();
for (const f of Object.keys(result.metafile.inputs)) {
    const i = f.lastIndexOf("node_modules/");
    if (i < 0) continue;
    const parts = f.slice(i + "node_modules/".length).split("/");
    pkgs.add(parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0]);
}

const sections = [];
for (const name of [...pkgs].sort()) {
    const dir = path.join("node_modules", name);
    const pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    const lic = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
    const text = lic ? fs.readFileSync(path.join(dir, lic), "utf8").trim() : `License: ${pj.license} (no license file shipped by the package)`;
    sections.push(`## ${name} ${pj.version} — ${pj.license}\n\n${pj.homepage ?? ""}\n\n\`\`\`\n${text}\n\`\`\``);
}

const header = `# Third-party notices

This program bundles the following open-source components into \`dist/index.js\`.
Generated by \`scripts/build.mjs\` from the packages actually included in the bundle.

## Search helper jar (\`helper/shamela-helper.jar\`)

Compiled from [alhoqbani/shamela-mcp](https://github.com/alhoqbani/shamela-mcp) (MIT,
license text below under \`shamela-mcp\`), taken unmodified from its official
release v1.3.0 (\`shamela-mcp-1.3.0.mcpb\`) by \`scripts/fetch-helper.mjs\`, which
verifies both checksums:

- release bundle SHA-256 \`24bcc1bed56e1f5ed22e59f1ed9840e682eef74b17845d288bb858e3e85e6c27\`
- helper jar SHA-256 \`a5f3e6caff34f208dd80ec16395f075e0c3c99840fc067e3b65b5eb7aba7a3ab\`

The jar contains only the upstream project's own classes. Apache Lucene and the
AlKhalil morphological analyzer are **not** shipped; they are loaded at runtime
from the user's own Shamela installation.

## Not included

No Shamela book, database, index or program file is included in this program
or its repository. All library content is read at runtime, read-only, from the
user's own installation.
`;
fs.writeFileSync("THIRD_PARTY_NOTICES.md", `${header}\n${sections.join("\n\n")}\n`);
console.log(`THIRD_PARTY_NOTICES.md: ${pkgs.size} bundled packages`);
